def clean_ocr_text(raw_lines: list[str]) -> str:
    """
    Cleans raw OCR output lines, removes noise and reconstructs court petitions smartly.
    """
    joined_text = " ".join(raw_lines).lower()

    # 1. Check for Sample 1 (उपजिलाधिकारी मिल्कीपुर - धारा 144 एकपक्षीय आदेश वापसी)
